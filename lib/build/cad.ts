import type { Cad, CadShape } from "./schema.ts";
import { partModel, type Prim } from "./models.ts";

/**
 * OpenSCAD export for generated projects. Pure, no DOM: the browser viewer (components/build/three-scene.ts)
 * reads the same validated model, so the file and the picture agree.
 *
 * Conventions: millimetres, Z up. A box is centred on `at`; a cylinder stands on the Z axis, centred on `at`.
 * `rotate` is [x, y, z] degrees about the shape's own centre, X first, then Y, then Z (as in OpenSCAD).
 * A box `radius` rounds its four vertical edges.
 */

const fmt = (n: number) => (Math.round(n * 1000) / 1000).toString();
const vec = (v: readonly number[]) => `[${v.map(fmt).join(", ")}]`;
const hex = (color: string) => color.replace(/[^#0-9a-fA-F]/g, "");
const rot = (r: readonly number[] | undefined, body: string) => (r && r.some((d) => d !== 0) ? `rotate(${vec(r)}) ${body}` : body);

function scadBody(s: CadShape): string {
  if (s.type === "cylinder") return `cylinder(r = ${fmt(s.r)}, h = ${fmt(s.h)}, center = true, $fn = 64);`;
  const r = Math.min(s.radius ?? 0, s.size[0] / 2 - 0.01, s.size[1] / 2 - 0.01);
  if (r <= 0.05) return `cube(${vec(s.size)}, center = true);`;
  const dx = s.size[0] / 2 - r, dy = s.size[1] / 2 - r;
  const corners = [[dx, dy], [-dx, dy], [-dx, -dy], [dx, -dy]].map(([x, y]) => `translate([${fmt(x!)}, ${fmt(y!)}, 0]) cylinder(r = ${fmt(r)}, h = ${fmt(s.size[2])}, center = true, $fn = 48);`);
  return `hull() { ${corners.join(" ")} }`;
}

const scadShape = (s: CadShape) => `translate(${vec(s.at)}) ${rot(s.rotate, scadBody(s))}`;

function scadPrim(p: Prim): string {
  const body = p.type === "box" ? `cube(${vec(p.size)}, center = true);`
    : p.type === "cylinder" ? `cylinder(r = ${fmt(p.r)}, h = ${fmt(p.h)}, center = true, $fn = 32);`
    : `sphere(r = ${fmt(p.r)}, $fn = 24);`;
  return `color("${hex(p.color)}") translate(${vec(p.at)}) ${rot("rotate" in p ? p.rotate : undefined, body)}`;
}

/** Module name from a part name: letters, digits and underscores only, never starting with a digit. */
export function scadModuleName(name: string, index: number): string {
  const base = name.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "").slice(0, 32);
  return `part_${index + 1}${base ? `_${base}` : ""}`;
}

/**
 * OpenSCAD source: one module per printed part (solids unioned, holes subtracted), bought parts as
 * see-through reference models (the % modifier: shown in preview, left out of F6 renders and STL exports),
 * then the assembled view. Render a single printed module with F6 and export it as STL for printing.
 */
export function toOpenScad(cad: Cad, title: string): string {
  const safeTitle = title.replace(/[\r\n*/]/g, " ").slice(0, 90);
  const lines = [`// ${safeTitle}`, "// Generated by the ropros AI Project Generator. Units: mm, Z up.", "// Check every dimension against your real parts before printing.", ""];
  cad.parts.forEach((part, i) => {
    const name = scadModuleName(part.name, i);
    lines.push(`// ${part.name.replace(/[\r\n]/g, " ")}${part.component ? ` (bought: ${part.component})` : part.printed ? " (3D printed)" : ""}`);
    lines.push(`module ${name}() {`);
    if (part.component) {
      const at = part.at ?? [0, 0, 0];
      lines.push(`  translate(${vec(at)}) ${rot(part.rotate, "{")}`, ...partModel(part.component).prims.map((p) => `    ${scadPrim(p)}`), "  }");
    } else {
      const shapes = part.shapes ?? [];
      const solids = shapes.filter((s) => !s.subtract).map(scadShape);
      const holes = shapes.filter((s) => s.subtract).map(scadShape);
      if (holes.length) lines.push("  difference() {", "    union() {", ...solids.map((s) => `      ${s}`), "    }", ...holes.map((s) => `    ${s}`), "  }");
      else lines.push("  union() {", ...solids.map((s) => `    ${s}`), "  }");
    }
    lines.push("}", "");
  });
  lines.push("// Assembled view");
  cad.parts.forEach((part, i) => lines.push(part.component
    ? `% ${scadModuleName(part.name, i)}();`
    : `color("${hex(part.color)}") ${scadModuleName(part.name, i)}();`));
  return `${lines.join("\n")}\n`;
}
