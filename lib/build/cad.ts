import type { Cad, CadShape } from "./schema.ts";

/**
 * CAD helpers for generated projects. Pure functions, no DOM: the viewer, the .scad export and the
 * .stl export all read the same validated model (lib/build/schema.ts), so they always agree.
 *
 * Conventions: millimetres, Z up. A box is centred on `at`; a cylinder stands on the Z axis, centred on `at`.
 * `rotate` is [x, y, z] degrees applied about the shape's own centre, X first, then Y, then Z (as in OpenSCAD).
 */

export type Vec3 = [number, number, number];
export type Triangle = { a: Vec3; b: Vec3; c: Vec3; part: number; subtract: boolean };

const SEGMENTS = 28;
const fmt = (n: number) => (Math.round(n * 1000) / 1000).toString();
const vec = (v: readonly number[]) => `[${v.map(fmt).join(", ")}]`;
const hex = (color: string) => color.replace(/[^#0-9a-fA-F]/g, "");

// ---------------------------------------------------------------- OpenSCAD

function scadShape(s: CadShape): string {
  const body = s.type === "box"
    ? `cube(${vec(s.size)}, center = true);`
    : `cylinder(r = ${fmt(s.r)}, h = ${fmt(s.h)}, center = true, $fn = 64);`;
  const rotated = s.rotate && s.rotate.some((d) => d !== 0) ? `rotate(${vec(s.rotate)}) ${body}` : body;
  return `translate(${vec(s.at)}) ${rotated}`;
}

/** Module name from a part name: letters, digits and underscores only, never starting with a digit. */
export function scadModuleName(name: string, index: number): string {
  const base = name.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "").slice(0, 32);
  return `part_${index + 1}${base ? `_${base}` : ""}`;
}

/**
 * OpenSCAD source with one module per part (solid shapes unioned, then holes subtracted), followed by the
 * assembled view. Open it in OpenSCAD, render a single module with F6 and export it as STL for printing.
 */
export function toOpenScad(cad: Cad, title: string): string {
  const safeTitle = title.replace(/[\r\n*/]/g, " ").slice(0, 90);
  const lines = [`// ${safeTitle}`, "// Generated by the ropros AI Project Generator. Units: mm, Z up.", "// Check every dimension against your real parts before printing.", ""];
  cad.parts.forEach((part, i) => {
    const solids = part.shapes.filter((s) => !s.subtract).map(scadShape);
    const holes = part.shapes.filter((s) => s.subtract).map(scadShape);
    lines.push(`// ${part.name.replace(/[\r\n]/g, " ")}${part.printed ? " (3D printed)" : ""}`);
    lines.push(`module ${scadModuleName(part.name, i)}() {`);
    if (holes.length) {
      lines.push("  difference() {", "    union() {", ...solids.map((s) => `      ${s}`), "    }", ...holes.map((s) => `    ${s}`), "  }");
    } else {
      lines.push("  union() {", ...solids.map((s) => `    ${s}`), "  }");
    }
    lines.push("}", "");
  });
  lines.push("// Assembled view");
  cad.parts.forEach((part, i) => lines.push(`color("${hex(part.color)}") ${scadModuleName(part.name, i)}();`));
  return `${lines.join("\n")}\n`;
}

// ---------------------------------------------------------------- mesh

const rad = (d: number) => (d * Math.PI) / 180;

function rotate(p: Vec3, r: readonly number[] | undefined): Vec3 {
  if (!r) return p;
  let [x, y, z] = p;
  const [ax, ay, az] = r.map(rad) as Vec3;
  [y, z] = [y * Math.cos(ax) - z * Math.sin(ax), y * Math.sin(ax) + z * Math.cos(ax)];
  [x, z] = [x * Math.cos(ay) + z * Math.sin(ay), -x * Math.sin(ay) + z * Math.cos(ay)];
  [x, y] = [x * Math.cos(az) - y * Math.sin(az), x * Math.sin(az) + y * Math.cos(az)];
  return [x, y, z];
}

/** Triangles of one primitive in world space, wound counter-clockwise when seen from outside. */
function shapeTriangles(s: CadShape): [Vec3, Vec3, Vec3][] {
  const place = (p: Vec3): Vec3 => { const q = rotate(p, s.rotate); return [q[0] + s.at[0], q[1] + s.at[1], q[2] + s.at[2]]; };
  const out: [Vec3, Vec3, Vec3][] = [];
  const quad = (a: Vec3, b: Vec3, c: Vec3, d: Vec3) => { out.push([a, b, c], [a, c, d]); };
  if (s.type === "box") {
    const [hx, hy, hz] = s.size.map((v) => v / 2) as Vec3;
    const v = (x: number, y: number, z: number) => place([x * hx, y * hy, z * hz]);
    quad(v(-1, -1, -1), v(-1, 1, -1), v(1, 1, -1), v(1, -1, -1));   // bottom
    quad(v(-1, -1, 1), v(1, -1, 1), v(1, 1, 1), v(-1, 1, 1));       // top
    quad(v(-1, -1, -1), v(1, -1, -1), v(1, -1, 1), v(-1, -1, 1));   // front (-y)
    quad(v(1, 1, -1), v(-1, 1, -1), v(-1, 1, 1), v(1, 1, 1));       // back (+y)
    quad(v(-1, 1, -1), v(-1, -1, -1), v(-1, -1, 1), v(-1, 1, 1));   // left (-x)
    quad(v(1, -1, -1), v(1, 1, -1), v(1, 1, 1), v(1, -1, 1));       // right (+x)
    return out;
  }
  const h = s.h / 2;
  const ring = (z: number) => Array.from({ length: SEGMENTS }, (_, i) => {
    const a = (i / SEGMENTS) * Math.PI * 2;
    return place([s.r * Math.cos(a), s.r * Math.sin(a), z]);
  });
  const lo = ring(-h), hi = ring(h);
  const cLo = place([0, 0, -h]), cHi = place([0, 0, h]);
  for (let i = 0; i < SEGMENTS; i++) {
    const j = (i + 1) % SEGMENTS;
    quad(lo[i]!, lo[j]!, hi[j]!, hi[i]!);
    out.push([cHi, hi[i]!, hi[j]!], [cLo, lo[j]!, lo[i]!]);
  }
  return out;
}

/** Every triangle of the model, tagged with its part index and whether it belongs to a hole. */
export function cadTriangles(cad: Cad): Triangle[] {
  return cad.parts.flatMap((part, i) => part.shapes.flatMap((s) =>
    shapeTriangles(s).map(([a, b, c]) => ({ a, b, c, part: i, subtract: Boolean(s.subtract) }))));
}

/** Axis-aligned bounds of the solid shapes (holes ignored); used to centre and scale the viewer. */
export function cadBounds(tris: readonly Triangle[]): { min: Vec3; max: Vec3 } {
  const min: Vec3 = [Infinity, Infinity, Infinity], max: Vec3 = [-Infinity, -Infinity, -Infinity];
  for (const t of tris) {
    if (t.subtract) continue;
    for (const p of [t.a, t.b, t.c]) for (let k = 0; k < 3; k++) { min[k] = Math.min(min[k]!, p[k]!); max[k] = Math.max(max[k]!, p[k]!); }
  }
  if (!Number.isFinite(min[0])) return { min: [0, 0, 0], max: [0, 0, 0] };
  return { min, max };
}

const normal = (a: Vec3, b: Vec3, c: Vec3): Vec3 => {
  const u = [b[0] - a[0], b[1] - a[1], b[2] - a[2]], v = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
  const n: Vec3 = [u[1]! * v[2]! - u[2]! * v[1]!, u[2]! * v[0]! - u[0]! * v[2]!, u[0]! * v[1]! - u[1]! * v[0]!];
  const len = Math.hypot(...n) || 1;
  return [n[0] / len, n[1] / len, n[2] / len];
};

/**
 * ASCII STL of the solid shapes of the chosen parts. Holes are not cut here (that needs CSG):
 * the STL is for a quick look in a slicer, the .scad file is the exact model.
 */
export function toStl(cad: Cad, partIndexes?: readonly number[]): string {
  const keep = partIndexes ? new Set(partIndexes) : undefined;
  const facets = cadTriangles(cad)
    .filter((t) => !t.subtract && (!keep || keep.has(t.part)))
    .map(({ a, b, c }) => `facet normal ${normal(a, b, c).map(fmt).join(" ")}\n outer loop\n  vertex ${a.map(fmt).join(" ")}\n  vertex ${b.map(fmt).join(" ")}\n  vertex ${c.map(fmt).join(" ")}\n endloop\nendfacet`);
  return `solid ropros\n${facets.join("\n")}\nendsolid ropros\n`;
}

/** Face normal, exposed for the viewer's lighting. */
export const faceNormal = normal;
