/** Writes supabase/seed-guides.sql: one published public.projects row per guide (needed for XP / progress).
 *  node --experimental-strip-types scripts/guides-seed.ts */
import fs from "node:fs";
import { allGuideSlugs, getGuide } from "../lib/guides.ts";
import { getComponent } from "../lib/hardware/components.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows = allGuideSlugs().map((slug) => {
  const g = getGuide(slug)!;
  const comps = [...new Set(g.parts.filter((p) => !p.component || getComponent(p.component).kind !== "mechanical").map((p) => p.name))].slice(0, 40);
  return `  (${q(g.slug)}, ${q(g.title.en.slice(0, 120))}, ${q(g.platform)}, ${q(g.difficulty)}, array[${comps.map(q).join(",")}], ${g.xpReward}, true)`;
});
const sql = `-- Generated by scripts/guides-seed.ts: one published catalogue row per guide (safe to re-run).
insert into public.projects (slug, title, platform, difficulty, components_required, xp_reward, is_published) values
${rows.join(",\n")}
on conflict (slug) do update set
  title = excluded.title, platform = excluded.platform, difficulty = excluded.difficulty,
  components_required = excluded.components_required, xp_reward = excluded.xp_reward, is_published = true;
`;
fs.writeFileSync(new URL("../supabase/seed-guides.sql", import.meta.url), sql);
console.log(`supabase/seed-guides.sql: ${rows.length} rows`);
