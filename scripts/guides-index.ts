/** Regenerates content/guides/index.ts (every guide file) and content/guides/catalog.ts (card fields only)
 *  from the guide files in that folder.
 *  node --experimental-strip-types scripts/guides-index.ts */
import fs from "node:fs";
import type { GuideContent } from "../lib/content/schema.ts";
import { getComponent } from "../lib/hardware/components.ts";

const dir = new URL("../content/guides/", import.meta.url);
const files = fs.readdirSync(dir).filter((f) => /^[a-z0-9-]+\.ts$/.test(f) && !["index.ts", "catalog.ts", "slugs.ts", "finder.ts"].includes(f)).sort();
const ident = (f: string) => "g_" + f.replace(/\.ts$/, "").replace(/-/g, "_");

/** What a card, the hub search and the parts finder need: a few KB per guide instead of the whole guide. */
export function catalogEntry(g: GuideContent) {
  return {
    slug: g.slug, platform: g.platform, board: g.board, boardName: getComponent(g.board).name, category: g.category, robotics: g.robotics,
    difficulty: g.difficulty, hours: g.hours, title: g.title, summary: g.summary,
    parts: g.parts.map((p) => ({ component: p.component, name: getComponent(p.component).name, qty: p.qty, ...(p.optional ? { optional: true as const } : {}) })),
  };
}

/** What the parts finder needs, and nothing else: it runs in the browser. */
export function finderEntry(g: GuideContent) {
  return {
    slug: g.slug, title: g.title, boardName: getComponent(g.board).name, board: g.board,
    parts: g.parts.map((p) => ({ component: p.component, name: getComponent(p.component).name, ...(p.optional ? { optional: true as const } : {}) })),
  };
}

// Writes only when run directly; tests import catalogEntry() without touching the files.
if (import.meta.url === `file://${process.argv[1]}`) {
  const index = `// Generated by scripts/guides-index.ts. Do not edit by hand.
import type { GuideContent } from "../../lib/content/schema.ts";
${files.map((f) => `import ${ident(f)} from "./${f}";`).join("\n")}

export const CONTENT_GUIDES: GuideContent[] = [
${files.map((f) => `  ${ident(f)},`).join("\n")}
];
`;
  fs.writeFileSync(new URL("index.ts", dir), index);
  const guides: GuideContent[] = [];
  for (const f of files) guides.push((await import(new URL(f, dir).href)).default as GuideContent);
  const catalog = `// Generated by scripts/guides-index.ts. Do not edit by hand.
import type { GuideCard } from "../../lib/content/catalog.ts";

export const GUIDE_CATALOG: GuideCard[] = [
${guides.map((g) => `  ${JSON.stringify(catalogEntry(g))},`).join("\n")}
];
`;
  fs.writeFileSync(new URL("catalog.ts", dir), catalog);
  const finder = guides.map(finderEntry);
  fs.writeFileSync(new URL("finder.ts", dir), `// Generated by scripts/guides-index.ts. Do not edit by hand.\nimport type { FinderGuide } from "../../lib/content/catalog.ts";\n\nexport const FINDER_GUIDES: FinderGuide[] = [\n${finder.map((f) => `  ${JSON.stringify(f)},`).join("\n")}\n];\n`);
  // Every guide page that exists (the hand-written ones in lib/guides.ts too), for the 404 check in proxy.ts.
  const { allGuideSlugs } = await import("../lib/guides.ts");
  fs.writeFileSync(new URL("slugs.ts", dir), `// Generated by scripts/guides-index.ts. Do not edit by hand.\nexport const GUIDE_SLUG_LIST: readonly string[] = ${JSON.stringify(allGuideSlugs())};\n`);
  console.log(`content/guides/index.ts, catalog.ts, finder.ts, slugs.ts: ${files.length} guides`);
}
