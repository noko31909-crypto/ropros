/** Regenerates content/guides/index.ts from the guide files in that folder.
 *  node --experimental-strip-types scripts/guides-index.ts */
import fs from "node:fs";
const dir = new URL("../content/guides/", import.meta.url);
const files = fs.readdirSync(dir).filter((f) => /^[a-z0-9-]+\.ts$/.test(f) && f !== "index.ts").sort();
const ident = (f: string) => "g_" + f.replace(/\.ts$/, "").replace(/-/g, "_");
const out = `// Generated by scripts/guides-index.ts. Do not edit by hand.
import type { GuideContent } from "../../lib/content/schema.ts";
${files.map((f) => `import ${ident(f)} from "./${f}";`).join("\n")}

export const CONTENT_GUIDES: GuideContent[] = [
${files.map((f) => `  ${ident(f)},`).join("\n")}
];
`;
fs.writeFileSync(new URL("index.ts", dir), out);
console.log(`content/guides/index.ts: ${files.length} guides`);
